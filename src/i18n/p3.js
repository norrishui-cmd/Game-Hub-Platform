export function p3Text(locale, key, vars = {}) {
  let value = (P3[locale] || P3.en)[key] ?? P3.en[key] ?? key;
  for (const [name, replacement] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, replacement);
  return value;
}
